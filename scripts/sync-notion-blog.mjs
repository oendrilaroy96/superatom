// Pulls published blog posts from a Notion database at build time and writes
// them out as static data the site reads (runs automatically before
// `npm run dev` and `npm run build`).
//
// Needs two environment variables (Cloudflare Pages project settings, or a
// local .env.local file):
//   NOTION_TOKEN             - secret of a Notion integration shared with the database
//   NOTION_BLOG_DATABASE_ID  - ID of the blog database
// Without them the sync is skipped and the blog shows its placeholder content.
//
// Database properties it reads (names are case-insensitive):
//   <title property>  post title (whatever the title column is called)
//   Status            select/status; only "Published" posts are synced
//   Slug              optional; generated from the title when empty
//   Category          optional select
//   Publish Date      optional date (or "Date"); future dates are held back
//   Excerpt           optional text (or "Summary"); first paragraph otherwise
//   Featured          optional checkbox; marks the post shown at the top
// The page cover becomes the post's cover image.

import { existsSync } from "node:fs";
import { mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const INDEX_FILE = path.join(root, "src/generated/blogIndex.ts");
const DATA_DIR = path.join(root, "public/blog-data");
const POSTS_DIR = path.join(DATA_DIR, "posts");
const IMAGES_DIR = path.join(DATA_DIR, "images");
const PUBLIC_IMAGES_PATH = "/blog-data/images";

const envFile = path.join(root, ".env.local");
if (existsSync(envFile)) {
  if (typeof process.loadEnvFile === "function") {
    process.loadEnvFile(envFile);
  } else {
    console.warn(
      `[blog] Found .env.local but this Node.js (${process.version}) can't read it. Update to Node 20.12 or newer.`,
    );
  }
}

const token = process.env.NOTION_TOKEN;
const databaseId = process.env.NOTION_BLOG_DATABASE_ID;

async function writeIndex(index) {
  await mkdir(path.dirname(INDEX_FILE), { recursive: true });
  await writeFile(
    INDEX_FILE,
    `// Generated by scripts/sync-notion-blog.mjs. Do not edit by hand.\n` +
      `import type { BlogIndex } from "../lib/blog";\n\n` +
      `export const blogIndex: BlogIndex = ${JSON.stringify(index, null, 2)};\n`,
  );
}

if (!token || !databaseId) {
  console.warn("[blog] NOTION_TOKEN or NOTION_BLOG_DATABASE_ID not set, skipping Notion sync.");
  // Keep whatever an earlier sync produced; only create an empty index if none exists.
  if (!existsSync(INDEX_FILE)) await writeIndex({ source: "none", posts: [] });
  process.exit(0);
}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function notion(endpoint, { method = "GET", body } = {}) {
  for (let attempt = 0; ; attempt++) {
    const res = await fetch(`https://api.notion.com/v1${endpoint}`, {
      method,
      headers: {
        Authorization: `Bearer ${token}`,
        "Notion-Version": "2022-06-28",
        "Content-Type": "application/json",
      },
      body: body ? JSON.stringify(body) : undefined,
    });
    // Notion rate-limits to a few requests per second; back off and retry.
    if ((res.status === 429 || res.status >= 500) && attempt < 5) {
      const retryAfter = Number(res.headers.get("retry-after"));
      await sleep((retryAfter > 0 ? retryAfter : 2 ** attempt) * 1000);
      continue;
    }
    if (!res.ok) {
      throw new Error(`Notion API ${method} ${endpoint} failed (${res.status}): ${await res.text()}`);
    }
    return res.json();
  }
}

async function paginate(fetchPage) {
  const results = [];
  let cursor;
  do {
    const data = await fetchPage(cursor);
    results.push(...data.results);
    cursor = data.has_more ? data.next_cursor : undefined;
  } while (cursor);
  return results;
}

const queryDatabase = () =>
  paginate((cursor) =>
    notion(`/databases/${databaseId}/query`, {
      method: "POST",
      body: { page_size: 100, ...(cursor && { start_cursor: cursor }) },
    }),
  );

const blockChildren = (blockId) =>
  paginate((cursor) =>
    notion(`/blocks/${blockId}/children?page_size=100${cursor ? `&start_cursor=${cursor}` : ""}`),
  );

// ---------- property helpers ----------

const plain = (richText = []) => richText.map((r) => r.plain_text).join("");

function findProperty(page, names, type) {
  for (const [key, value] of Object.entries(page.properties)) {
    if (names.includes(key.trim().toLowerCase()) && (!type || value.type === type)) return value;
  }
  return undefined;
}

function choiceName(prop) {
  if (!prop) return null;
  if (prop.type === "status") return prop.status?.name ?? null;
  if (prop.type === "select") return prop.select?.name ?? null;
  if (prop.type === "multi_select") return prop.multi_select?.[0]?.name ?? null;
  if (prop.type === "rich_text") return plain(prop.rich_text) || null;
  return null;
}

function textValue(prop) {
  if (prop?.type === "rich_text") return plain(prop.rich_text).trim();
  if (prop?.type === "title") return plain(prop.title).trim();
  return "";
}

function isPublished(page) {
  const status = findProperty(page, ["status"]);
  if (status?.type === "checkbox") return status.checkbox;
  return choiceName(status)?.trim().toLowerCase() === "published";
}

function slugify(text) {
  return text
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

// ---------- images ----------

const IMAGE_EXTENSIONS = {
  "image/png": "png",
  "image/jpeg": "jpg",
  "image/gif": "gif",
  "image/webp": "webp",
  "image/svg+xml": "svg",
  "image/avif": "avif",
};

// Notion-hosted file URLs expire after about an hour, so they are downloaded
// and served from the site itself. External image URLs are used as-is.
async function resolveImage(file, name) {
  if (!file) return null;
  if (file.type === "external") return file.external.url;
  if (file.type !== "file") return null;
  const res = await fetch(file.file.url);
  if (!res.ok) throw new Error(`Image download failed (${res.status}) for ${name}`);
  const contentType = res.headers.get("content-type")?.split(";")[0].trim() ?? "";
  const ext =
    IMAGE_EXTENSIONS[contentType] ??
    (path.extname(new URL(file.file.url).pathname).slice(1).toLowerCase() || "img");
  const filename = `${name}.${ext}`;
  await writeFile(path.join(IMAGES_DIR, filename), Buffer.from(await res.arrayBuffer()));
  return `${PUBLIC_IMAGES_PATH}/${filename}`;
}

// ---------- blocks ----------

function richText(items = []) {
  return items.map((r) => {
    const out = { text: r.plain_text };
    if (r.href) out.href = r.href;
    for (const flag of ["bold", "italic", "strikethrough", "underline", "code"]) {
      if (r.annotations?.[flag]) out[flag] = true;
    }
    return out;
  });
}

const unsupported = new Set();

async function convertBlocks(pageId) {
  const blocks = [];
  for (const block of await blockChildren(pageId)) {
    const data = block[block.type];
    switch (block.type) {
      case "paragraph":
        if (data.rich_text.length) blocks.push({ type: "paragraph", text: richText(data.rich_text) });
        break;
      case "heading_1":
      case "heading_2":
      case "heading_3":
        // The post title is the page's only h1, so Notion headings shift down a level.
        blocks.push({ type: "heading", level: Number(block.type.at(-1)) + 1, text: richText(data.rich_text) });
        break;
      case "bulleted_list_item":
      case "numbered_list_item": {
        const ordered = block.type === "numbered_list_item";
        const last = blocks.at(-1);
        const item = richText(data.rich_text);
        if (last?.type === "list" && last.ordered === ordered) last.items.push(item);
        else blocks.push({ type: "list", ordered, items: [item] });
        break;
      }
      case "quote":
        blocks.push({ type: "quote", text: richText(data.rich_text) });
        break;
      case "callout":
        blocks.push({
          type: "callout",
          text: richText(data.rich_text),
          ...(data.icon?.type === "emoji" && { icon: data.icon.emoji }),
        });
        break;
      case "code":
        blocks.push({ type: "code", code: plain(data.rich_text), language: data.language });
        break;
      case "image": {
        const src = await resolveImage(data, block.id);
        if (src) {
          blocks.push({ type: "image", src, ...(data.caption?.length && { caption: richText(data.caption) }) });
        }
        break;
      }
      case "divider":
        blocks.push({ type: "divider" });
        break;
      default:
        unsupported.add(block.type);
    }
  }
  return blocks;
}

function blockText(block) {
  if (block.type === "list") return block.items.flat().map((r) => r.text).join(" ");
  if ("text" in block) return block.text.map((r) => r.text).join("");
  return "";
}

function excerptFrom(blocks) {
  const first = blocks.find((b) => b.type === "paragraph");
  const text = first ? blockText(first).replace(/\s+/g, " ").trim() : "";
  if (text.length <= 180) return text;
  return `${text.slice(0, 180).replace(/\s+\S*$/, "")}…`;
}

// ---------- main ----------

const now = new Date();
const pages = await queryDatabase();
const published = pages.filter((page) => {
  if (page.archived || page.in_trash || !isPublished(page)) return false;
  const date = findProperty(page, ["publish date", "published", "date"], "date")?.date?.start;
  return !date || new Date(date) <= now;
});

await rm(DATA_DIR, { recursive: true, force: true });
await mkdir(POSTS_DIR, { recursive: true });
await mkdir(IMAGES_DIR, { recursive: true });

const usedSlugs = new Set();
const summaries = [];

for (const page of published) {
  const title = plain(Object.values(page.properties).find((p) => p.type === "title")?.title).trim();
  if (!title) continue;

  const baseSlug = slugify(textValue(findProperty(page, ["slug"])) || title) || page.id;
  let slug = baseSlug;
  for (let n = 2; usedSlugs.has(slug); n++) slug = `${baseSlug}-${n}`;
  usedSlugs.add(slug);

  const blocks = await convertBlocks(page.id);
  const words = blocks.map(blockText).join(" ").split(/\s+/).filter(Boolean).length;

  const summary = {
    slug,
    title,
    excerpt: textValue(findProperty(page, ["excerpt", "summary", "description"])) || excerptFrom(blocks),
    category: choiceName(findProperty(page, ["category", "tag", "tags"])),
    date: findProperty(page, ["publish date", "published", "date"], "date")?.date?.start ?? null,
    readMinutes: Math.max(1, Math.round(words / 225)),
    cover: await resolveImage(page.cover, `${page.id}-cover`),
    featured: findProperty(page, ["featured"], "checkbox")?.checkbox ?? false,
  };

  summaries.push(summary);
  await writeFile(path.join(POSTS_DIR, `${slug}.json`), JSON.stringify({ ...summary, blocks }));
}

summaries.sort((a, b) => (b.date ?? "").localeCompare(a.date ?? ""));
await writeIndex({ source: "notion", posts: summaries });

console.log(`[blog] Synced ${summaries.length} published post(s) from Notion.`);
if (unsupported.size) {
  console.warn(`[blog] Skipped unsupported Notion block types: ${[...unsupported].join(", ")}`);
}
